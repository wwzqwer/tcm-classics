  let TABLE = null;   // 合并后的完整繁简表（内置 + data/s2t.json）

  async function init() {
    if (TABLE) return;
    let ext = {};
    try {
      ext = await App.loadJSON("data/s2t.json");
    } catch (e) {
      ext = {};
    }
    TABLE = Object.assign({}, MAP, ext);  // 外部完整表覆盖内置表
  }

  function normalize(text) {
    const T = TABLE || MAP;
    let out = "";
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      const pair = ch + (text[i + 1] || "");
      if (T[pair]) { out += T[pair]; i++; }
      else out += T[ch] || ch;
    }
    return out;
  }

  function expandTerms(query) {
    const q = normalize(query);
    return q.split(/[\s,，、;；。|]+/).filter(t => t.length >= 1);
  }

  /* 全库检索：先精确（多词同段），不足时降级为「任一词命中 + 命中数排序」 */
  const normCache = {};
  async function scan(terms, mode, limit) {
    const books = await App.loadJSON("data/books/index.json");
    const results = [];
    for (const meta of books) {
      if (!normCache[meta.id]) {
        const book = await App.loadJSON("data/books/" + meta.id + ".json");
        normCache[meta.id] = {
          title: book.title,
          chapters: book.chapters.map(c => ({
            title: c.title,
            paras: c.paras.map(p => ({ raw: p, norm: normalize(p) }))
          }))
        };
      }
      const data = normCache[meta.id];
      for (const ch of data.chapters) {
        for (const p of ch.paras) {
          let hit = 0;
          for (const t of terms) if (p.norm.includes(t)) hit++;
          const pass = mode === "and" ? hit === terms.length : hit > 0;
          if (pass) {
            results.push({
              bookId: meta.id, bookTitle: data.title, chapter: ch.title,
              snippet: makeSnippet(p.raw, terms, 130),
              hits: hit,
            });
            if (mode === "and" && results.length >= limit) return results;
          }
        }
      }
    }
    return results;
  }

  async function searchAll(query, limit = 50) {
    const terms = expandTerms(query).filter(t => t.length > 0);
    if (!terms.length) return [];
    let results = await scan(terms, "and", limit);
    if (results.length < Math.min(5, limit) && terms.length > 1) {
      // 多词同段命中不足：降级为 OR，按命中词数排序
      const orResults = await scan(terms, "or", limit * 6);
      orResults.sort((a, b) => b.hits - a.hits || a.snippet.length - b.snippet.length);
      results = orResults.slice(0, limit);
    }
    return results;
  }

  function makeSnippet(raw, terms, width) {
    const norm = normalize(raw);
    let pos = -1;
    for (const t of terms) { pos = norm.indexOf(t); if (pos >= 0) break; }
    const start = Math.max(0, pos - 40);
    const end = Math.min(raw.length, pos + width);
    return (start > 0 ? "……" : "") + raw.slice(start, end) + (end < raw.length ? "……" : "");
  }

  return { normalize, expandTerms, searchAll, init };
